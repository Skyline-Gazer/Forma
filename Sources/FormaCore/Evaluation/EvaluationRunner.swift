import CryptoKit
import Foundation

/// Runs a gold dataset through the real mapping path and reports what happened,
/// without a provider.
///
/// The composition is deliberate: the runner owns the batch plan (`MappingEngine`'s
/// own `plannedBatches`, so the grouping, the opaque refs and the attached rows are
/// the ones a real run would build), the validation (`ManifestValidator`), the
/// judgement (`CaseJudgement`) and the gate (`EvaluationReport`). What it replaces
/// is one seam only - `MappingAnswering` - and the caller states what answers:
/// a `SubstituteAnswerer` for an offline run, or `ProviderMappingClient` for the
/// live path that P3-B still has to authorise.
///
/// The runner has no provider of its own and constructs none, so "默认禁止真实 Provider
/// 请求" is a property of the type rather than a flag someone has to remember. Nothing in
/// this file can open a socket, load a key, or read a file: the sample fixtures are
/// synthetic by construction (`EvaluationFixture`), and the evidence rows they cite are
/// generated by the harness, not read from disk.
public enum EvaluationRunner {
    /// The bounds a run executes under.
    public struct Configuration: Sendable {
        public let profile: MappingProfile
        /// The model the run is configured against. Recorded even for a stand-in
        /// run as the configuration, and *not* published as the identity's model
        /// when a stand-in answered, because no model produced those answers.
        public let model: String
        public let provider: ProbeProvider
        /// False by default: a cloud request is a separate decision from running
        /// the harness, and the default has to be the one that sends nothing.
        public let allowCloud: Bool
        public let maximumConcurrency: Int
        public let perRequestTimeout: Duration
        public let retry: RetryPolicy
        public let entryLimit: Int
        public let bootstrapResamples: Int
        public let bootstrapSeed: UInt64
        public let redaction: RedactionPlan
        /// The price set any cost is computed with, or nil when the caller has
        /// none. FormaCore ships no prices.
        public let pricing: TokenPricing?

        public init(profile: MappingProfile, model: String, provider: ProbeProvider = .anthropic,
                    allowCloud: Bool = false, maximumConcurrency: Int = 4,
                    perRequestTimeout: Duration = .seconds(30), retry: RetryPolicy = .default,
                    entryLimit: Int = MappingPrompt.defaultEntryLimit,
                    bootstrapResamples: Int = 200, bootstrapSeed: UInt64 = 0x9E37_79B9_7F4A_7C15,
                    redaction: RedactionPlan = .none, pricing: TokenPricing? = nil) {
            // A non-positive deadline would cancel every request before it started
            // and then report a 100% timeout rate, which reads as a provider
            // problem rather than a configuration one.
            self.profile = profile
            self.model = model
            self.provider = provider
            self.allowCloud = allowCloud
            self.maximumConcurrency = max(1, maximumConcurrency)
            self.perRequestTimeout = max(.milliseconds(1), perRequestTimeout)
            self.retry = retry
            self.entryLimit = max(1, entryLimit)
            self.bootstrapResamples = max(1, bootstrapResamples)
            self.bootstrapSeed = bootstrapSeed
            self.redaction = redaction
            self.pricing = pricing
        }
    }

    /// Bounded retry with exponential backoff.
    ///
    /// `maximumAttempts` counts the first ask, so a policy that allows three
    /// attempts is one ask plus two retries - the same arithmetic the live client
    /// uses for its repair round, and the reason `retries` is derived rather than
    /// configured.
    public struct RetryPolicy: Sendable, Equatable {
        public let maximumAttempts: Int
        public let initialBackoff: Duration
        public let multiplier: Double
        public let maximumBackoff: Duration

        public static let disabled = RetryPolicy(maximumAttempts: 1, initialBackoff: .zero,
                                                 multiplier: 1, maximumBackoff: .zero)
        public static let `default` = RetryPolicy(maximumAttempts: 3, initialBackoff: .milliseconds(200),
                                                  multiplier: 2, maximumBackoff: .seconds(5))

        public init(maximumAttempts: Int = 3, initialBackoff: Duration = .milliseconds(200),
                    multiplier: Double = 2, maximumBackoff: Duration = .seconds(5)) {
            precondition(maximumAttempts >= 1, "a policy with zero attempts issues no request")
            precondition(multiplier >= 1, "a backoff multiplier below one shortens the wait on every retry")
            self.maximumAttempts = maximumAttempts
            self.initialBackoff = max(.zero, initialBackoff)
            self.multiplier = multiplier
            self.maximumBackoff = max(.zero, maximumBackoff)
        }

        public var retries: Int { maximumAttempts - 1 }

        /// Whether a failure is worth another call.
        ///
        /// Cancellation is the one that never is: the task has already been told to
        /// stop, and re-issuing a request on its behalf is the only retry that
        /// cannot be taken back.
        public func isRetryable(_ error: FormaError) -> Bool {
            switch error {
            case .timeout, .network, .disconnected, .unavailable, .invalidResponse, .invalidOutput:
                return true
            case .remoteStatus(let status):
                return status == 429 || status >= 500
            case .cancelled, .refused, .unauthorized, .credentialMissing, .incompatible, .storage,
                 .invalidSource, .sourceChanged, .hydrationPending:
                return false
            }
        }

        /// The wait before retry number `retry`, which is one-based. Doubles from
        /// `initialBackoff` and never exceeds `maximumBackoff`.
        public func backoff(for retry: Int) -> Duration {
            guard retry >= 1, maximumBackoff > .zero else { return .zero }
            let waited = Double(Self.milliseconds(initialBackoff)) * pow(multiplier, Double(retry - 1))
            let capped = min(Double(Self.milliseconds(maximumBackoff)), waited)
            return .milliseconds(Int64(capped))
        }

        static func milliseconds(_ duration: Duration) -> Int64 {
            let parts = duration.components
            return parts.seconds * 1_000 + parts.attoseconds / 1_000_000_000_000_000
        }
    }

    // MARK: - Entry point

    /// Execute `dataset` and return the manifest, the judged cases, the execution
    /// telemetry and the report, in one value.
    ///
    /// Throws only when the run cannot be described honestly: a dataset whose
    /// countable set is not disjoint from its prompt side, or one project cluster
    /// whose reference answers name two different projects. A provider failure is
    /// not thrown - it is an outcome recorded per request and counted in the
    /// denominators, because PLAN §8.2 keeps a failed extraction in `total` and
    /// reports it as `hold` instead of dropping it.
    public static func run(dataset: GoldDataset, answerer: any MappingAnswering,
                           configuration: Configuration) async throws -> EvaluationRun {
        let startedAt = Date()
        let profile = configuration.profile
        let casePack = dataset.casePack
        let report = dataset.report()

        // The split already guarantees that the three lists are disjoint; stating it
        // here is what makes the boundary this runner enforces explicit instead of
        // inherited from whoever built the dataset.
        guard dataset.countableIDs.isDisjoint(with: dataset.split.promptRecordIDs) else {
            throw FormaError.incompatible
        }

        // Only the countable set. A record the split withdrew, or left prompt-side,
        // has no denominator here, and reaching it through `records` would put
        // material the model has seen into a score.
        let countable = dataset.records
            .filter { dataset.countableIDs.contains($0.recordID) }
            .sorted { $0.recordID < $1.recordID }

        let scopeID = EvaluationFixture.uuid("forma.evaluation.scope.v1",
                                             "\(dataset.split.splitID)|\(dataset.split.datasetRevision)")
        let rootID = EvaluationFixture.uuid("forma.evaluation.root.v1", scopeID.uuidString)

        // One project cluster is one candidate, and every reference answer in it
        // must name the same project: `CaseJudgement` resolves a candidate ref to
        // one key, so a cluster naming two projects would have no honest table.
        var projectByCluster: [String: String] = [:]
        var samples: [EvaluationSample] = []
        for record in countable {
            let cluster = record.source.projectClusterKey
            let project = record.expected.projectReference ?? cluster
            if let existing = projectByCluster[cluster], existing != project {
                throw FormaError.incompatible
            }
            projectByCluster[cluster] = project
            samples.append(try EvaluationSample(record: record, rootID: rootID, projectKey: project))
        }
        let recordIDsBySource = Dictionary(uniqueKeysWithValues: samples.map { ($0.entry.id, $0.record.recordID) })

        let entries = samples.map(\.entry)
        let evidence = Dictionary(uniqueKeysWithValues: samples.map { ($0.entry.id, $0.evidence) })
        let grouped = Dictionary(grouping: samples, by: \.candidateID)
        let candidates: [ContextCandidate] = grouped.keys.sorted().compactMap { key in
            guard let members = grouped[key], let first = members.first else { return nil }
            return ContextCandidate(id: key, projectKey: first.projectKey, displayName: nil,
                                    basis: [.directory],
                                    memberSourceIDs: Set(members.map { $0.entry.id }),
                                    confidence: .medium)
        }
        let context = ProjectContext(
            revision: 1, scopeID: scopeID, profileID: profile.profileID,
            profileVersion: profile.profileVersion,
            inputDigest: ContextBuilder.inputDigest(scopeID: scopeID, profile: profile, entries: entries),
            candidates: candidates, unassignedSourceIDs: [], conflictedSourceIDs: [], builtAt: startedAt)
        let projectKeys = Dictionary(uniqueKeysWithValues: candidates.map { ($0.id, $0.projectKey) })

        // The batch plan comes from the engine rather than from a second grouping
        // written here: the membership, the refs and the attached evidence rows are
        // what a real run would send, so a request digest computed from them means
        // something.
        let batches = MappingEngine.plannedBatches(from: entries, context: context,
                                                   limit: configuration.entryLimit, evidence: evidence)

        let execution = await Self.execute(batches: batches, answerer: answerer, configuration: configuration,
                                           profile: profile, context: context, casePack: casePack,
                                           recordIDsBySource: recordIDsBySource)

        // Merge answers exactly as the engine does: an unknown `entry_ref` is
        // refused rather than matched by name, and a request failure is applied
        // only to entries no answer reached.
        var proposals: [UUID: ProposalForEntry] = [:]
        var refusedReferences = 0
        for batch in batches {
            guard let outcome = execution.requests[batch.id] else { continue }
            var refs: [String: UUID] = [:]
            for entry in batch.entries { refs[entry.ref] = entry.sourceID }
            if let proposal = outcome.proposal {
                for entry in proposal.entries {
                    guard let sourceID = refs[entry.entryRef] else { refusedReferences += 1; continue }
                    proposals[sourceID] = ProposalForEntry(sourceID: sourceID, proposal: entry)
                }
            }
            guard let error = outcome.failure else { continue }
            for entry in batch.entries where proposals[entry.sourceID] == nil {
                proposals[entry.sourceID] = ProposalForEntry(sourceID: entry.sourceID, proposal: nil,
                                                             failure: error)
            }
        }

        let ordered = proposals.values.sorted { $0.sourceID.uuidString < $1.sourceID.uuidString }
        let validation = ManifestValidator(ValidationInput(profile: profile, context: context, entries: entries,
                                                           evidence: evidence, proposals: ordered)).validate()

        let counts = validation.report.counts
        let state: ManifestEnvelope.ManifestState
        if counts.validated == 0 {
            state = .draft
        } else if counts.validated == counts.entries {
            state = .validated
        } else {
            state = .partiallyValidated
        }

        let isSubstitute = answerer.isSubstitute
        let runID = Self.runDigest(dataset: dataset, configuration: configuration, samples: samples,
                                   isSubstitute: isSubstitute)
        // A stand-in never contacted the provider, so the manifest and the report
        // name the stand-in rather than a model that produced nothing.
        let identity = EvaluationRunIdentity(
            goldRevision: dataset.split.datasetRevision, splitID: dataset.split.splitID,
            casePackID: dataset.split.casePack.id, casePackVersion: dataset.split.casePack.version,
            profileVersionKeys: [profile.profileID: profile.profileVersion],
            provider: isSubstitute ? "substitute" : configuration.provider.rawValue,
            modelID: isSubstitute ? nil : configuration.model,
            isSubstitute: isSubstitute,
            bootstrapResamples: configuration.bootstrapResamples, bootstrapSeed: configuration.bootstrapSeed)

        let envelope = ManifestEnvelope(
            manifestID: EvaluationFixture.uuid("forma.evaluation.manifest.v1", runID),
            revision: 1, supersedesRevision: nil, scopeID: scopeID, sourceRootID: rootID,
            profile: profile, casePack: (casePack.id, casePack.version),
            modelProvider: identity.provider, modelID: identity.modelID,
            contextRevision: context.revision, promptVersion: MappingPrompt.version,
            extractorVersion: EvidenceRegistry.extractorVersion,
            redactionVersion: configuration.redaction.isIdentity ? nil : RedactionPlan.version,
            inputDigest: context.inputDigest, contextDigest: MappingEngine.contextDigest(context),
            createdAt: startedAt, state: state)
        let manifest = Manifest(envelope: envelope, entries: validation.entries, report: validation.report)

        let cases = samples.map { sample in
            CaseJudgement(gold: sample.record, entry: manifest.entry(for: sample.entry.id),
                          projectKeys: projectKeys)
        }

        let telemetry = Self.telemetry(execution: execution, samples: samples, batches: batches,
                                       configuration: configuration, pricing: configuration.pricing,
                                       substitute: isSubstitute)
        let boundary = EvaluationBoundary(
            datasetRecords: report.totalRecords, countable: report.countableRecords,
            evaluated: samples.count, promptSideRecords: dataset.split.promptRecordIDs.count,
            withdrawnRecords: dataset.split.removed.count, pendingAdjudication: report.pendingAdjudication,
            unaccountedRecords: report.unaccountedRecords)

        return EvaluationRun(
            runID: runID, identity: identity, boundary: boundary, manifest: manifest, cases: cases,
            telemetry: telemetry,
            requests: batches.compactMap { execution.requests[$0.id]?.observation },
            refusedReferences: refusedReferences,
            report: EvaluationReport(cases: cases, identity: identity, dataset: report))
    }

    // MARK: - Execution

    /// What one request did: its attempts, its accounting, and the answer that
    /// decided it.
    private struct RequestExecution: Sendable {
        let observation: EvaluationRequestObservation
        let proposal: MappingProposal?
        let failure: FormaError?
        let usage: TokenUsage
        let outcome: MappingOutcome
        let attemptsTimedOut: Int
        let attemptsCancelled: Int
    }

    /// The outcome of one call to the answerer.
    private struct AttemptOutcome: Sendable {
        /// Nil only when the deadline won and the cancelled call returned nothing
        /// at all. A cancelled call that still returns its own accounting keeps it.
        let attempt: MappingAttempt?
        let timedOut: Bool
    }

    private struct Execution: Sendable {
        let requests: [String: RequestExecution]
        let observedConcurrency: Int
        let cancelled: Bool
        let wallClockMilliseconds: Int
    }

    private static func execute(batches: [MappingBatch], answerer: any MappingAnswering,
                                configuration: Configuration, profile: MappingProfile,
                                context: ProjectContext, casePack: CasePack,
                                recordIDsBySource: [UUID: String]) async -> Execution {
        let limit = max(1, configuration.maximumConcurrency)
        let start = ContinuousClock.now
        var outcomes: [String: RequestExecution] = [:]
        var iterator = batches.makeIterator()
        var inFlight = 0
        var observed = 0
        var cancelled = false

        await withTaskGroup(of: (String, RequestExecution).self) { group in
            var next = iterator.next()
            while next != nil || inFlight > 0 {
                if Task.isCancelled {
                    // The caller is gone. Requests already in flight are cancelled
                    // and awaited by the group; the ones not yet issued are counted
                    // as never issued rather than as failed requests.
                    group.cancelAll()
                    cancelled = true
                    break
                }
                while let batch = next, inFlight < limit {
                    inFlight += 1
                    observed = max(observed, inFlight)
                    let assigned = batch
                    group.addTask {
                        (assigned.id, await Self.execute(batch: assigned, answerer: answerer,
                                                         configuration: configuration, profile: profile,
                                                         context: context, casePack: casePack,
                                                         recordIDsBySource: recordIDsBySource))
                    }
                    next = iterator.next()
                }
                guard let (id, outcome) = await group.next() else { break }
                outcomes[id] = outcome
                inFlight -= 1
            }
        }

        return Execution(requests: outcomes, observedConcurrency: observed, cancelled: cancelled,
                         wallClockMilliseconds: Int(Self.milliseconds(start.duration(to: .now))))
    }

    private static func execute(batch: MappingBatch, answerer: any MappingAnswering,
                                configuration: Configuration, profile: MappingProfile,
                                context: ProjectContext, casePack: CasePack,
                                recordIDsBySource: [UUID: String]) async -> RequestExecution {
        let recordIDs = batch.entries.compactMap { recordIDsBySource[$0.sourceID] }
        let digest = (try? ProviderMappingClient.preview(profile: profile, context: context, casePack: casePack,
                                                         batch: batch, redaction: configuration.redaction))?.digest
            ?? ""
        let start = ContinuousClock.now

        var attempts = 0
        var providerRequests = 0
        var retries = 0
        var attemptsTimedOut = 0
        var attemptsCancelled = 0
        var failure: FormaError?
        var proposal: MappingProposal?
        var usage = TokenUsage.unavailable
        var providerLatency: Int?
        var firstToken: Int?
        var outcome = MappingOutcome.truncated

        while !Task.isCancelled {
            attempts += 1
            let result = await Self.attempt(batch: batch, answerer: answerer, configuration: configuration,
                                            profile: profile, context: context, casePack: casePack)
            if result.timedOut {
                attemptsTimedOut += 1
                // A request that outlived its deadline still reached the provider, so
                // whatever the cancelled call reports is kept; nothing is invented
                // when it reports nothing.
                if let attempt = result.attempt {
                    providerRequests += attempt.requests
                    usage = usage.added(to: Self.usage(of: attempt.usage, substitute: answerer.isSubstitute))
                    providerLatency = Self.latency(of: attempt)
                    firstToken = attempt.timeToFirstTokenMilliseconds ?? firstToken
                }
                failure = .timeout
                outcome = .timeout
                if configuration.retry.isRetryable(.timeout), attempts < configuration.retry.maximumAttempts {
                    retries += 1
                    do {
                        try await Task.sleep(for: configuration.retry.backoff(for: retries))
                    } catch {
                        failure = .cancelled
                        outcome = .cancelled
                        break
                    }
                    continue
                }
                break
            }
            guard let attempt = result.attempt else {
                // Neither an answer nor a deadline: the call was cancelled from
                // outside, and there is nothing to retry.
                attemptsCancelled += 1
                failure = .cancelled
                outcome = .cancelled
                break
            }
            providerRequests += attempt.requests
            usage = usage.added(to: Self.usage(of: attempt.usage, substitute: answerer.isSubstitute))
            if let latency = Self.latency(of: attempt) { providerLatency = latency }
            firstToken = attempt.timeToFirstTokenMilliseconds ?? firstToken
            outcome = attempt.outcome
            failure = attempt.error
            proposal = attempt.proposal ?? proposal
            if attempt.outcome == .cancelled { attemptsCancelled += 1 }
            guard let error = attempt.error,
                  configuration.retry.isRetryable(error),
                  attempts < configuration.retry.maximumAttempts else { break }
            retries += 1
            do {
                try await Task.sleep(for: configuration.retry.backoff(for: retries))
            } catch {
                failure = .cancelled
                outcome = .cancelled
                break
            }
        }

        if Task.isCancelled, failure == nil {
            failure = .cancelled
            outcome = .cancelled
        }

        let wallClock = Int(Self.milliseconds(start.duration(to: .now)))
        let observation = EvaluationRequestObservation(
            requestID: batch.id, candidateID: batch.candidateID, recordIDs: recordIDs,
            attempts: attempts, providerRequests: providerRequests, retried: retries > 0,
            outcome: outcome.rawValue, errorCode: failure?.code, wallClockMilliseconds: wallClock,
            providerLatencyMilliseconds: providerLatency, firstTokenMilliseconds: firstToken,
            usage: usage, payloadDigest: digest)
        return RequestExecution(observation: observation, proposal: proposal, failure: failure, usage: usage,
                                outcome: outcome, attemptsTimedOut: attemptsTimedOut,
                                attemptsCancelled: attemptsCancelled)
    }

    /// One call to the answerer under the per-request deadline.
    ///
    /// The deadline is a task racing the call rather than a timeout parameter the
    /// answerer is trusted to honour: a provider that never returns has to be
    /// bounded by the runner, not by the provider's own good behaviour. When the
    /// deadline wins, the call is cancelled and whatever accounting it still
    /// returns is kept - a request that was billed must not vanish from the
    /// telemetry because somebody stopped waiting for it.
    private static func attempt(batch: MappingBatch, answerer: any MappingAnswering,
                                configuration: Configuration, profile: MappingProfile,
                                context: ProjectContext, casePack: CasePack) async -> AttemptOutcome {
        await withTaskGroup(of: AttemptOutcome.self) { group in
            group.addTask {
                let attempt = await answerer.answer(provider: configuration.provider, model: configuration.model,
                                                    allowCloud: configuration.allowCloud, profile: profile,
                                                    context: context, casePack: casePack, batch: batch,
                                                    redaction: configuration.redaction)
                return AttemptOutcome(attempt: attempt, timedOut: false)
            }
            group.addTask {
                do {
                    try await Task.sleep(for: configuration.perRequestTimeout)
                } catch {
                    // Cancelled because the call finished first; the call's own
                    // result is the one that matters and this task contributes
                    // nothing to the race.
                }
                return AttemptOutcome(attempt: nil, timedOut: true)
            }
            guard var first = await group.next() else {
                return AttemptOutcome(attempt: nil, timedOut: true)
            }
            group.cancelAll()
            if first.timedOut {
                // Keep whatever the cancelled call reports. `MappingAnswering` is
                // required to observe cancellation, so this is bounded by the
                // answerer's own cancellation path rather than by the deadline.
                while let rest = await group.next() {
                    if let attempt = rest.attempt {
                        first = AttemptOutcome(attempt: attempt, timedOut: true)
                    }
                }
            }
            return first
        }
    }

    // MARK: - Telemetry

    private static func telemetry(execution: Execution, samples: [EvaluationSample], batches: [MappingBatch],
                                  configuration: Configuration, pricing: TokenPricing?,
                                  substitute: Bool) -> EvaluationTelemetry {
        let ordered = batches.compactMap { execution.requests[$0.id] }
        var usage = TokenUsage.unavailable
        var latency: [Int] = []
        var firstToken: [Int] = []
        var attemptCount = 0
        var providerRequests = 0
        var retryCount = 0
        var timedOut = 0
        var cancelled = 0
        var succeeded = 0
        for request in ordered {
            usage = usage.added(to: request.usage)
            attemptCount += request.observation.attempts
            providerRequests += request.observation.providerRequests
            retryCount += max(0, request.observation.attempts - 1)
            timedOut += request.attemptsTimedOut
            cancelled += request.attemptsCancelled
            if request.outcome == .ok { succeeded += 1 }
            if let latencyMilliseconds = request.observation.providerLatencyMilliseconds,
               latencyMilliseconds > 0 {
                latency.append(latencyMilliseconds)
            }
            if let first = request.observation.firstTokenMilliseconds {
                firstToken.append(first)
            }
        }
        let failed = ordered.count - succeeded
        let wallClock = execution.wallClockMilliseconds
        let throughput = wallClock > 0 ? Double(samples.count) / (Double(wallClock) / 1_000) : nil
        let provenance: MeasurementKind = substitute ? .simulated : .measured

        return EvaluationTelemetry(
            sampleCount: samples.count, requestCount: batches.count, issuedRequestCount: ordered.count,
            attemptCount: attemptCount, providerRequestCount: providerRequests, retryCount: retryCount,
            timedOutAttempts: timedOut, cancelledAttempts: cancelled, succeededRequests: succeeded,
            failedRequests: failed, maximumConcurrency: configuration.maximumConcurrency,
            observedConcurrency: execution.observedConcurrency, wallClockMilliseconds: wallClock,
            throughputSamplesPerSecond: throughput, usage: usage,
            latency: LatencyDistribution(samples: latency, kind: provenance),
            firstToken: FirstTokenLatency(samples: firstToken, kind: provenance),
            cost: CostEstimate.estimate(usage: usage, pricing: pricing, sampleCount: samples.count),
            cancelled: execution.cancelled)
    }

    /// The attempt's own counts, labelled by who produced them. A stand-in's usage
    /// is `simulated` whatever numbers it carries, which is the whole point of the
    /// flag: the same arithmetic must never be publishable as a provider's.
    private static func usage(of usage: MappingUsage, substitute: Bool) -> TokenUsage {
        TokenUsage(input: usage.input, output: usage.output, cacheRead: usage.cacheRead,
                   cacheCreation: usage.cacheCreation, kind: substitute ? .simulated : .measured)
    }

    /// A provider that reported zero milliseconds reported nothing: zero is the
    /// field's default, not an observation, and a run of instant answers must not
    /// publish a p50 of 0 ms as if it had measured one.
    private static func latency(of attempt: MappingAttempt) -> Int? {
        attempt.latencyMilliseconds > 0 ? attempt.latencyMilliseconds : nil
    }

    static func milliseconds(_ duration: Duration) -> Int64 {
        RetryPolicy.milliseconds(duration)
    }

    private static func runDigest(dataset: GoldDataset, configuration: Configuration,
                                  samples: [EvaluationSample], isSubstitute: Bool) -> String {
        // One material string rather than one `hasher.update` per field: the
        // concatenations are what a reader compares across runs, and building them
        // apart from the hash keeps the digest's inputs readable.
        var material = "forma.evaluation.run.v1"
        material += "|\(dataset.split.splitID)|\(dataset.split.datasetRevision)"
        material += "|\(dataset.split.casePack.id)|\(dataset.split.casePack.version)"
        material += "|\(configuration.profile.profileID)|\(configuration.profile.profileVersion)"
        material += "|provider=\(isSubstitute ? "substitute" : configuration.provider.rawValue)"
        material += "|model=\(isSubstitute ? "-" : configuration.model)"
        material += "|cloud=\(configuration.allowCloud)"
        material += "|concurrency=\(configuration.maximumConcurrency)"
        material += "|timeout_ms=\(milliseconds(configuration.perRequestTimeout))"
        material += "|entry_limit=\(configuration.entryLimit)"
        material += "|resamples=\(configuration.bootstrapResamples)"
        material += "|seed=\(configuration.bootstrapSeed)"
        material += "|retry=\(configuration.retry.maximumAttempts)"
        material += "|\(milliseconds(configuration.retry.initialBackoff))"
        material += "|\(configuration.retry.multiplier)"
        material += "|\(milliseconds(configuration.retry.maximumBackoff))"
        material += "|pricing=\(configuration.pricing?.id ?? CostEstimate.unpriced)"
        for sample in samples {
            material += "|\(sample.record.recordID)|\(sample.entry.id.uuidString)"
        }
        return String(SHA256.hash(data: Data(material.utf8)).hexadecimalDigest.prefix(32))
    }
}

/// One gold record as the runner presents it to the mapping path: a synthetic
/// source entry, its candidate, and the evidence rows its reference answer can be
/// supported by.
struct EvaluationSample: Sendable {
    let record: GoldRecord
    let entry: SourceEntry
    let candidateID: String
    let projectKey: String
    let evidence: [EvidenceRecord]

    init(record: GoldRecord, rootID: UUID, projectKey: String) throws {
        self.record = record
        self.candidateID = EvaluationFixture.candidateID(for: record.source.projectClusterKey)
        self.projectKey = projectKey
        self.entry = EvaluationFixture.entry(for: record, rootID: rootID)
        self.evidence = try EvaluationFixture.evidence(for: record)
    }
}

/// The synthetic fixtures every evaluation sample is built from.
///
/// They are synthetic on purpose, and they are derived rather than random: a
/// record id gives the same source id, snapshot fingerprint and evidence ids on
/// every run, so two runs of one dataset ask the same question and a request
/// digest can be compared across them. Nothing here touches the filesystem - the
/// entries are `present` and local because a file the run never read cannot be
/// anything else, and their size, mtime and hash are left nil because nobody
/// measured them.
enum EvaluationFixture {
    static let snapshotRevision: Int = 1

    /// Evidence rows the harness invents are stamped with the harness's own epoch
    /// rather than a read time: no file was read, and a plausible-looking timestamp
    /// would be a claim about one.
    static let fixtureDate = Date(timeIntervalSince1970: 0)

    /// The same record always names the same source, so two runs of one dataset
    /// ask the same question and the manifest ids match.
    static func sourceID(for recordID: String) -> UUID {
        uuid("forma.evaluation.source.v1", recordID)
    }

    /// The value the reference answer states for a slot.
    ///
    /// `GoldRecord` carries the category and the document type inside `metadata`,
    /// and the category and type are also stated at the top level as
    /// `target_category` / `target_type`. A record that states only the top-level
    /// one has still stated it, so the harness reads both and the stand-in can
    /// answer - and cite - what the reference answer actually says.
    static func expected(_ record: GoldRecord, _ field: MetadataFieldID) -> String? {
        switch field {
        case .documentcategory: return record.expected.metadata[field] ?? record.expected.targetCategory
        case .documenttype: return record.expected.metadata[field] ?? record.expected.targetType
        default: return record.expected.metadata[field]
        }
    }

    static func fingerprint(for recordID: String) -> String {
        String(SHA256.hash(data: Data("forma.evaluation.snapshot.v1|\(recordID)".utf8))
            .hexadecimalDigest.prefix(64))
    }

    static func candidateID(for clusterKey: String) -> String {
        "cand-" + String(SHA256.hash(data: Data("forma.evaluation.candidate.v1|\(clusterKey)".utf8))
            .hexadecimalDigest.prefix(12))
    }

    /// A locator that is stable per field and unique across the twelve: the page is
    /// the field's position, so no two fields of one record cite the same row.
    static func locator(for field: MetadataFieldID, length: Int) -> EvidenceLocator {
        let page = (MetadataFieldID.allCases.firstIndex(of: field) ?? 0) + 1
        return .pdf(page: page, characterRange: 0..<max(1, length))
    }

    static func entry(for record: GoldRecord, rootID: UUID) -> SourceEntry {
        let id = sourceID(for: record.recordID)
        return SourceEntry(
            id: id, rootID: rootID, relativePath: record.source.redactedRelativePath,
            normalizedRelativePath: record.source.redactedRelativePath, state: .present,
            hydrationPending: false, sourceVersion: 1, snapshotRevision: Int64(snapshotRevision),
            provider: .local, snapshotFingerprint: fingerprint(for: record.recordID),
            sizeBytes: nil, modificationTimeNanoseconds: nil, sha256: nil)
    }

    /// One content row per expected value. A slot the reference answer leaves empty
    /// gets no row, which is what makes "withheld" reachable: the validator rejects
    /// a value with no citation, so there is no way to fill it without evidence.
    static func evidence(for record: GoldRecord) throws -> [EvidenceRecord] {
        let id = sourceID(for: record.recordID)
        let fingerprint = fingerprint(for: record.recordID)
        var rows: [EvidenceRecord] = []
        for field in MetadataFieldID.allCases {
            guard let value = EvaluationFixture.expected(record, field), !value.isEmpty else { continue }
            let locator = locator(for: field, length: value.count)
            let evidenceID = try EvidenceRegistry.identifier(
                sourceID: id, snapshotRevision: snapshotRevision, source: .content, locator: locator,
                relativePath: nil)
            rows.append(EvidenceRecord(
                id: evidenceID, sourceID: id, snapshotRevision: snapshotRevision,
                snapshotFingerprint: fingerprint, source: .content, locator: locator, relativePath: nil,
                excerpt: value, extractionStatus: .ok, extractorVersion: EvidenceRegistry.extractorVersion,
                createdAt: fixtureDate))
        }
        return rows
    }

    static func uuid(_ namespace: String, _ value: String) -> UUID {
        let digest = SHA256.hash(data: Data("\(namespace)|\(value)".utf8))
        var bytes = Array(digest.prefix(16))
        // A name-based (version 5) UUID: the value is derived, so the same dataset
        // names the same ids in another process, which a random UUID would not.
        bytes[6] = (bytes[6] & 0x0F) | 0x50
        bytes[8] = (bytes[8] & 0x3F) | 0x80
        return UUID(uuid: (bytes[0], bytes[1], bytes[2], bytes[3], bytes[4], bytes[5], bytes[6], bytes[7],
                           bytes[8], bytes[9], bytes[10], bytes[11], bytes[12], bytes[13], bytes[14], bytes[15]))
    }
}

/// What the dataset kept out of the run, and why.
///
/// The count of scored records is not the count of records in the directory, and a
/// report that prints only the first invites a reader to assume the rest were
/// scored. Each exclusion is a number with a name: prompt-side material the model
/// has seen, material the split withdrew, material still in adjudication, and
/// records the split accounts for nowhere.
public struct EvaluationBoundary: Codable, Sendable, Equatable {
    public let datasetRecords: Int
    public let countable: Int
    public let evaluated: Int
    public let promptSideRecords: Int
    public let withdrawnRecords: Int
    public let pendingAdjudication: Int
    public let unaccountedRecords: [String]

    enum CodingKeys: String, CodingKey {
        case datasetRecords = "dataset_records", countable, evaluated
        case promptSideRecords = "prompt_side_records", withdrawnRecords = "withdrawn_records"
        case pendingAdjudication = "pending_adjudication", unaccountedRecords = "unaccounted_records"
    }
}

/// The exportable form of a run.
///
/// Deliberately not the manifest: the manifest carries relative paths, group
/// paths and evidence excerpts, and a shareable report must not. What travels is
/// the identity, the boundary, the execution facts and the rates - everything a
/// reviewer needs to decide whether the run can be quoted, and nothing that
/// identifies a customer's documents.
public struct EvaluationArtifact: Codable, Sendable, Equatable {
    public let schemaVersion: String
    public let runID: String
    public let identity: EvaluationRunIdentity
    public let boundary: EvaluationBoundary
    public let telemetry: EvaluationTelemetry
    public let report: EvaluationReport

    enum CodingKeys: String, CodingKey {
        case schemaVersion = "schema_version", runID = "run_id", identity, boundary, telemetry, report
    }

    public init(schemaVersion: String = "1.0", runID: String, identity: EvaluationRunIdentity,
                boundary: EvaluationBoundary, telemetry: EvaluationTelemetry, report: EvaluationReport) {
        self.schemaVersion = schemaVersion
        self.runID = runID
        self.identity = identity
        self.boundary = boundary
        self.telemetry = telemetry
        self.report = report
    }
}

/// One executed run: the manifest, the judged cases, and everything needed to
/// decide whether the numbers may be quoted.
public struct EvaluationRun: Sendable {
    /// Derived from the dataset, the configuration and the sample set, so the same
    /// run re-executed produces the same identifier and the same manifest id.
    public let runID: String
    public let identity: EvaluationRunIdentity
    public let boundary: EvaluationBoundary
    public let manifest: Manifest
    public let cases: [CaseJudgement]
    public let telemetry: EvaluationTelemetry
    /// One row per issued request, in batch order.
    public let requests: [EvaluationRequestObservation]
    /// Answers that named an `entry_ref` the run never issued.
    public let refusedReferences: Int
    /// The rates and the gate, computed once from the cases above.
    public let report: EvaluationReport

    /// The §6 gate, re-stated for callers that only hold the run.
    public var isQualityClaimAllowed: Bool { report.isQualityClaimAllowed }

    public var artifact: EvaluationArtifact {
        EvaluationArtifact(runID: runID, identity: identity, boundary: boundary, telemetry: telemetry,
                           report: report)
    }

    /// The run as JSON, for a shareable report.
    ///
    /// The report layer already refuses to let a stand-in or a thin sample carry a
    /// quality claim, so the exported bytes carry the refusal with the numbers
    /// instead of a summary that dropped it.
    public func export() throws -> Data {
        try FormaJSON.encode(artifact, pretty: true)
    }
}